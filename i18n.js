const LANG_KEY = "hok-lang";

function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    return saved === "en" ? "en" : "id";
  } catch {
    return "id";
  }
}

function setLang(lang) {
  const chosen = lang === "en" ? "en" : "id";
  try {
    localStorage.setItem(LANG_KEY, chosen);
  } catch {}

  if (typeof document !== "undefined") {
    document.documentElement.lang = chosen;
    // Update tombol saklar bahasa aktif di UI
    const btns = document.querySelectorAll(".lang-btn");
    btns.forEach(b => {
      const isCurrent = b.dataset.lang === chosen;
      b.classList.toggle("on", isCurrent);
      b.setAttribute("aria-pressed", String(isCurrent));
    });

    // Panggil re-render route aktif dan updateNav jika tersedia
    if (typeof window !== "undefined") {
      if (typeof window.updateNavLanguage === "function") {
        window.updateNavLanguage();
      }
      if (typeof window.route === "function") {
        window.route();
      }
    }
  }
}

function t(key, vars) {
  const lang = getLang();
  let str = (STRINGS[lang] && STRINGS[lang][key]);
  if (str == null) {
    // Fallback ke id jika en belum ada
    str = (STRINGS.id && STRINGS.id[key]);
  }
  if (str == null) {
    if (typeof console !== "undefined" && console.warn) {
      console.warn("[i18n] Missing translation for key:", key);
    }
    return key;
  }
  if (vars && typeof vars === "object") {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), v);
    }
  }
  return str;
}

